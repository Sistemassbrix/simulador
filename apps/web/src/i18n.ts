export function translate(text: string, lang: Language): string {
  if (lang !== 'en' || !text || typeof text !== 'string') return text;
  
  // Exact match
  if (translations[text]) return translations[text];

  const leading = text.match(/^\s*/)?.[0] || '';
  const trailing = text.match(/\s*$/)?.[0] || '';
  const trimmed = text.trim();
  if (!trimmed) return text;

  // Trimmed exact match
  if (translations[trimmed]) return leading + translations[trimmed] + trailing;

  // Normalized spaces match
  const norm = trimmed.replace(/\s+/g, ' ');
  if (translations[norm]) return leading + translations[norm] + trailing;

  // Dynamic regex patterns
  let m: RegExpMatchArray | null;

  if ((m = norm.match(/^Simulación Visual de Proceso \((?:Bache|Lote)\s*(\d+)\s*de\s*(\d+)\)$/i))) {
    return leading + 'Visual Process Simulation (Lot ' + m[1] + ' of ' + m[2] + ')' + trailing;
  }
  if ((m = norm.match(/^(?:Bache|Lote)\s*Actual:\s*(\d+)(?:\s*\/\s*(\d+))?$/i))) {
    return leading + 'Current Lot: ' + m[1] + (m[2] ? ' / ' + m[2] : '') + trailing;
  }
  if ((m = norm.match(/^Curva de Transición Vítrea \(Tg\) para (.*)$/i))) {
    const grain = m[1].trim();
    const grainTranslated = translations[grain] || grain;
    return leading + 'Glass Transition Curve (Tg) for ' + grainTranslated + trailing;
  }
  if ((m = norm.match(/^Detalles de (.*)$/i))) {
    return leading + 'Details of ' + m[1] + trailing;
  }
  if ((m = norm.match(/^Diesel:\s*(.*?)\s*L\/d[ií]a$/i))) {
    return leading + 'Diesel: ' + m[1] + ' L/day' + trailing;
  }
  if ((m = norm.match(/^Total:\s*(.*?)\s*Ton\/d[ií]a$/i))) {
    return leading + 'Total: ' + m[1] + ' Ton/day' + trailing;
  }
  if ((m = norm.match(/^(.*?)\s*Ton\/d[ií]a$/i))) {
    return leading + m[1] + ' Ton/day' + trailing;
  }
  if ((m = norm.match(/^(.*?)\s*\(Base comercializable\)$/i))) {
    return leading + m[1] + ' (Marketable basis)' + trailing;
  }
  if ((m = norm.match(/^(.*?)\s*horas\s+operativas$/i))) {
    return leading + m[1] + ' operating hours' + trailing;
  }
  if ((m = norm.match(/^(.*?)\s+seleccionados$/i))) {
    return leading + m[1] + ' selected' + trailing;
  }
  if ((m = norm.match(/^(.*?)\s+meses?\s+activos?$/i))) {
    return leading + m[1] + ' active month(s)' + trailing;
  }
  if ((m = norm.match(/^Aplicar\s+Meses\s*\((.*)\)$/i))) {
    return leading + 'Apply Months (' + m[1] + ')' + trailing;
  }
  if ((m = norm.match(/^Gestión de Maquinaria\s*\/\s*(.*)$/i))) {
    const cat = m[1] === 'Transportadores' ? 'Conveyors' : m[1] === 'Secadoras' ? 'Dryers' : m[1];
    return leading + 'Machinery Management / ' + cat + trailing;
  }
  if ((m = norm.match(/^Simulación Real de Producción - (.*)$/i))) {
    return leading + 'Real Production Simulation - ' + m[1] + trailing;
  }
  if ((m = norm.match(/^Se importaron los perfiles de clima para (.*)\. Por defecto se aplicó (.*)\.$/i))) {
    return leading + 'Imported weather profiles for ' + m[1] + '. Default applied: ' + m[2] + '.' + trailing;
  }
  if ((m = norm.match(/^Se han cargado los parámetros: Temperatura (.*)°C, Humedad Relativa (.*)%\.$/i))) {
    return leading + 'Parameters loaded: Temperature ' + m[1] + '°C, Relative Humidity ' + m[2] + '%.' + trailing;
  }
  if ((m = norm.match(/^Has creado (.*) escenarios en (.*) (.*) \(Total histórico: (.*)\)\.$/i))) {
    return leading + 'You created ' + m[1] + ' scenarios in ' + m[2] + ' ' + m[3] + ' (All-time total: ' + m[4] + ').' + trailing;
  }
  if ((m = norm.match(/^No se encontraron resultados para "(.*)"$/i))) {
    return leading + 'No results found for "' + m[1] + '"' + trailing;
  }
  if ((m = norm.match(/^Meses seleccionados:\s*(\d+)\s*\((.*)\)$/i))) {
    return leading + 'Selected months: ' + m[1] + ' (' + m[2] + ')' + trailing;
  }
  if ((m = norm.match(/^(\d+)\s+de\s+(\d+)\s+meses activos \(Año completo\)$/i))) {
    return leading + m[1] + ' of ' + m[2] + ' active months (Full year)' + trailing;
  }
  if ((m = norm.match(/^Extrayendo datos horarios \((.*)\) desde Open-Meteo\.\.\.$/i))) {
    return leading + 'Extracting hourly data (' + m[1] + ') from Open-Meteo...' + trailing;
  }

  if ((m = norm.match(/^Escenarios en (.*)$/i))) {
    const month = m[1].trim();
    const monthTranslated = translations[month] || month;
    return leading + 'Scenarios in ' + monthTranslated + trailing;
  }
  if ((m = norm.match(/^Mes en curso \((.*)\)$/i))) {
    return leading + 'Current month (' + m[1] + ')' + trailing;
  }
  if ((m = norm.match(/^Escenarios del Usuario \((.*)\)$/i))) {
    return leading + 'User Scenarios (' + m[1] + ')' + trailing;
  }
  if ((m = norm.match(/^Todos \((\d+)\)$/i))) {
    return leading + 'All (' + m[1] + ')' + trailing;
  }
  if ((m = norm.match(/^Activos \((\d+)\)$/i))) {
    return leading + 'Active (' + m[1] + ')' + trailing;
  }
  if ((m = norm.match(/^Borrados por usuario \((\d+)\)$/i))) {
    return leading + 'Deleted by user (' + m[1] + ')' + trailing;
  }
  if ((m = norm.match(/^(.*?)\s+kg\/t\s*\((.*?)\s*Ton\/d[ií]a\)$/i))) {
    return leading + m[1] + ' kg/t (' + m[2] + ' Ton/day)' + trailing;
  }

  if ((m = norm.match(/^Paso\s+(\d+)\s*\((.*?)\)$/i))) {
    const inner = translations[m[2].trim()] || (m[2].toLowerCase() === 'calor' ? 'Heat' : m[2]);
    return leading + 'Pass ' + m[1] + ' (' + inner + ')' + trailing;
  }
  if ((m = norm.match(/^Paso\s+(\d+)$/i))) {
    return leading + 'Pass ' + m[1] + trailing;
  }
  if ((m = norm.match(/^Atempero\s+(\d+)$/i))) {
    return leading + 'Tempering ' + m[1] + trailing;
  }
  if (/^Enfriamiento\s+Final$/i.test(norm)) {
    return leading + 'Final Cooling' + trailing;
  }
  if (/^Calor$/i.test(norm)) {
    return leading + 'Heat' + trailing;
  }
  if (/^Atempero$/i.test(norm)) {
    return leading + 'Tempering' + trailing;
  }
  if (/^Enfriamiento$/i.test(norm)) {
    return leading + 'Cooling' + trailing;
  }
  if (/^Operativo$/i.test(norm)) {
    return leading + 'Operating' + trailing;
  }

  return text;
}

